interface LanguageContextType {
  currentLang: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
  languages: LanguageInfo[];
}

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [currentLang, setCurrentLangState] = useState<LanguageCode>(() => {
    try {
      const saved = localStorage.getItem('app_language');
      if (saved && (saved === 'vi' || saved === 'en')) {
        return saved as LanguageCode;
      }
    } catch {}
    return 'vi';
  });

  const setLanguage = (lang: LanguageCode) => {
    setCurrentLangState(lang);
    try {
      localStorage.setItem('app_language', lang);
    } catch {}
  };

  const t = (key: string, fallback?: string): string => {
    const dict = TRANSLATIONS[currentLang] as Record<string, string>;
    if (dict && dict[key]) {
      return dict[key];
    }
    const viDict = TRANSLATIONS['vi'] as Record<string, string>;
    if (viDict && viDict[key]) {
      return viDict[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ currentLang, setLanguage, t, languages: WORLD_LANGUAGES }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};
